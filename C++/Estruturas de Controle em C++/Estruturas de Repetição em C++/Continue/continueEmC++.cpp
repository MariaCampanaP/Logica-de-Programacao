#include <bits/stdc++.h>

using namespace std;

// Continue --> Pula uma repetição

int main(){

    for(int i = 1; i <= 5; i++){
        if(i == 3){
            continue; //Quando o i for igual a 3 ele é pulado da repetição
        }

        cout << i << endl;

    }

    return 0;

}
