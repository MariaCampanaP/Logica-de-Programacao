#include <bits/stdc++.h>

using namespace std;

// Break --> Interrompe a repetição

int main(){

    for(int i = 1; i <= 10; i++){

        if(i == 5){
            break; // Interrompe a repetição quando o i for igual a 5
        }

        cout << i << endl;
    }

    return 0;

}
